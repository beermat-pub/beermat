// Expression tree, linear-syntax parser and printer, evaluator, units.
// Kotlin Multiplatform: the JVM (desktop app, CLI) and WebAssembly (the web version, docs/web.md).
// No UI dependencies, and no dependencies on other project modules.

import org.jetbrains.kotlin.gradle.ExperimentalWasmDsl

plugins {
    alias(libs.plugins.kotlin.multiplatform)
}

// The version (one number for the app, the CLI and the MCP server) and the unit table, as Kotlin
// source: resources aren't read the same way on every platform.
val generated = layout.buildDirectory.dir("generated/engine")
val generate by tasks.registering {
    val version = project.version.toString()
    val units = file("src/commonMain/resources/pub/beermat/engine/units.bbm")
    val dir = generated
    inputs.property("version", version)
    inputs.file(units)
    outputs.dir(dir)
    doLast {
        fun quoted(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        val lines = units.readLines().joinToString(",\n") { "    " + quoted(it) }
        dir.get().file("pub/beermat/engine/Generated.kt").asFile.apply { parentFile.mkdirs() }.writeText(
            """
            |// Generated by the engine's build (engine/build.gradle.kts): do not edit.
            |package pub.beermat.engine
            |
            |internal const val VERSION: String = ${quoted(version)}
            |
            |/** The text of units.bbm. */
            |internal val UNITS_BBM: String = listOf(
            |$lines,
            |).joinToString("\n")
            |""".trimMargin(),
        )
    }
}

kotlin {
    jvmToolchain(21)
    jvm()
    @OptIn(ExperimentalWasmDsl::class)
    wasmJs {
        nodejs()
    }
    compilerOptions {
        // expect/actual classes (HostFile) are still marked Beta.
        freeCompilerArgs.add("-Xexpect-actual-classes")
    }
    sourceSets {
        commonMain {
            kotlin.srcDir(generate)
        }
        commonTest.dependencies {
            implementation(kotlin("test"))
        }
    }
}

tasks.named<Test>("jvmTest") {
    useJUnitPlatform()
}
