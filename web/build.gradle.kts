// The web version (docs/web.md): the same sheet view as the desktop app, compiled to WebAssembly
// and run in a browser page, at beermat.pub/try.

import org.jetbrains.kotlin.gradle.ExperimentalWasmDsl

plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.compose.compiler)
    alias(libs.plugins.compose)
}

// The examples a visitor can open, from examples/, as Kotlin source (the page has no files of its own).
val generated = layout.buildDirectory.dir("generated/web")
val examples by tasks.registering {
    val sources = rootProject.layout.projectDirectory.dir("examples")
    val dir = generated
    inputs.dir(sources)
    outputs.dir(dir)
    doLast {
        // Line endings as \n, whatever the checkout wrote.
        fun quoted(s: String) = "\"" + s.replace("\r", "").replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$").replace("\n", "\\n") + "\""
        val files = sources.asFile.listFiles { f -> f.name.endsWith(".bbm") }!!.sortedBy { it.name }
        val entries = files.joinToString(",\n") { "    ${quoted(it.name)} to ${quoted(it.readText())}" }
        dir.get().file("pub/beermat/web/Examples.kt").asFile.apply { parentFile.mkdirs() }.writeText(
            "// Generated by web/build.gradle.kts from examples/: do not edit.\npackage pub.beermat.web\n\n" +
                "/** The examples, by file name. */\ninternal val EXAMPLES: List<Pair<String, String>> = listOf(\n$entries,\n)\n",
        )
    }
}

kotlin {
    @OptIn(ExperimentalWasmDsl::class)
    wasmJs {
        // The page loads web.js, named after the module.
        browser {
            testTask { enabled = false }
        }
        binaries.executable()
    }
    sourceSets {
        // One target, the browser: everything in commonMain, where Compose looks for the resources library.
        commonMain {
            kotlin.srcDir(examples)
            dependencies {
                implementation(project(":ui"))
                implementation(compose.runtime)
                implementation(compose.ui)
                implementation(compose.foundation)
                implementation(compose.components.resources)
                implementation(libs.kotlinx.browser)
            }
        }
    }
}

compose.resources {
    packageOfResClass = "pub.beermat.web.resources"
}
